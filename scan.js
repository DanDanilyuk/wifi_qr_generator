// Read-only view for guests: scan.html#ssid=...&security=...&password=...
import {
  SECURITY,
  buildWifiString,
  drawQr,
  normalizeSecurity,
  readLinkParams,
} from './wifi.js';

const $ = (id) => document.getElementById(id);

function showEmpty(heading, message) {
  $('scan-heading').textContent = heading;
  $('scan-body').hidden = true;
  $('scan-status').hidden = false;
  $('scan-status').textContent = message;
}

const params = readLinkParams(location);
const state = {
  ssid: params.get('ssid') || '',
  security: normalizeSecurity(params.get('security')),
  password: params.get('password') || '',
  hidden: params.get('hidden') === 'true',
};
const isOpen = state.security === 'nopass';

$('open-editor').href = `index.html${location.hash}`;

if (!state.ssid) {
  showEmpty(
    'No Wi-Fi details provided',
    'Open this page from a "Scan-only link" generated by the editor.'
  );
} else {
  try {
    drawQr($('qr'), buildWifiString(state));
    $('qr').setAttribute('aria-label', `Wi-Fi QR code for ${state.ssid}`);
    $('result-ssid').textContent = state.ssid;
    $('result-security').textContent = SECURITY[state.security].label;
    $('result-hidden-row').hidden = !state.hidden;
    $('result-password-row').hidden = isOpen;
    $('result-password').textContent = state.password || 'Not provided';
  } catch (error) {
    console.error(error);
    showEmpty(
      'This link is not valid',
      'The Wi-Fi details in this link are too long to fit in a QR code.'
    );
  }
}

// A new fragment means a different network, so start over.
window.addEventListener('hashchange', () => location.reload());
